def seg_dist(p, a, b):
    ax, ay = b[0] - a[0], b[1] - a[1]
    t = max(0.0, min(1.0, ((p[0] - a[0]) * ax + (p[1] - a[1]) * ay) / (ax * ax + ay * ay)))
    return math.hypot(p[0] - (a[0] + t * ax), p[1] - (a[1] + t * ay))


def rect(cx, cy, w, d, rot_deg, grow=0.0):
    """The corners of a footprint w x d centred at (cx, cy), its front facing rot_deg (180: width along x)."""
    th = math.radians(rot_deg - 180.0)
    c, s = math.cos(th), math.sin(th)
    pts = []
    for u, v in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
        x, y = u * (w / 2 + grow), v * (d / 2 + grow)
        pts.append((cx + x * c + y * s, cy - x * s + y * c))
    return pts


def overlap(a, b):
    """Two convex quads overlap (separating axis)."""
    for poly in (a, b):
        for i in range(4):
            x1, y1 = poly[i]
            x2, y2 = poly[(i + 1) % 4]
            nx, ny = y2 - y1, x1 - x2
            pa = [nx * x + ny * y for x, y in a]
            pb = [nx * x + ny * y for x, y in b]
            if max(pa) < min(pb) or max(pb) < min(pa):
                return False
    return True


