def b_seed(h, done, lanes):
    """A lower-town house's kit variant (IMP-019): among its kind's (its variant, storeys and party walls) the one used
    least so far, never one a neighbour of its kind within 25 m has, among those whose outside stair and whatever else
    it stands on the ground takes least of the side lanes (lane_cost)."""
    kind = (h["variant"], h["storeys"], h.get("party", ""))
    n = B_VARIANTS[h["storeys"]]
    kin = [o for o in done if (o["variant"], o["storeys"], o.get("party", "")) == kind]
    near = {o["seed"] for o in kin if math.hypot(o["pos"][0] - h["pos"][0], o["pos"][1] - h["pos"][1]) < 25.0}
    cost = {s: lane_cost(h, s, lanes) for s in range(1, n + 1)}
    clear = [s for s in cost if cost[s] == min(cost.values())]
    free = [s for s in clear if s not in near] or clear
    used = {s: sum(1 for o in kin if o["seed"] == s) for s in free}
    return random.Random(h["id"] + ":variant").choice([s for s in free if used[s] == min(used.values())])


def lane_cost(h, seed, lanes):
    """How much of the side lanes a town house with this kit variant would stand in: the points of each lane's walked
    band (from 0.5 m in to 0.4 m past its head, every 0.5 m, and 1 m either side, the room a walker needs; flight or
    not, as pads.py gives lanes flights the builder had none for) inside one of the variant's ground boxes (its outside
    stair, 0.35 m round, as tools/town/graph.py keeps walkers off them). Without the kit's sidecar, none."""
    f = "town_house_%s%s%s_v%d" % (h["variant"].lower(), "_s2" if h["storeys"] == 2 else "", "_" + h["party"] if "party" in h else "", seed)
    path = os.path.join(KIT, f + ".json")
    if not os.path.exists(path):
        return 0
    x, y, _ = h["pos"]
    th = math.radians(h["rot_deg"] - 180.0)
    c, s_ = math.cos(th), math.sin(th)
    boxes = []
    for g in json.load(open(path)).get("ground", []):  # each in the town grid, as graph.py's to_world turns it
        boxes.append([(x + u * c + v * s_, y - u * s_ + v * c) for u, v in ((g[0] - 0.35, g[1] - 0.35), (g[2] + 0.35, g[1] - 0.35),
                                                                           (g[2] + 0.35, g[3] + 0.35), (g[0] - 0.35, g[3] + 0.35))])
    hits = 0
    for ln in lanes:
        (fx, fy), (ux, uy) = ln["from"], ln["dir"]
        if math.hypot(fx - x, fy - y) > ln["length"] + 15.0:
            continue
        t = 0.5
        while t <= ln["length"] + 0.4:
            for off in (-1.0, -0.5, 0.0, 0.5, 1.0):
                px, py = fx + ux * t - uy * off, fy + uy * t + ux * off
                hits += any(inside(b, px, py) for b in boxes)
            t += 0.5
    return hits


def inside(poly, x, y):
    """Whether (x, y) is inside the polygon (even-odd rule)."""
    hit = False
    for i in range(len(poly)):
        (x1, y1), (x2, y2) = poly[i], poly[(i + 1) % len(poly)]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            hit = not hit
    return hit


def a_seed(hid, variant, x, y, houses, allowed):
    """An upper-town house's kit variant (IMP-019): its own draw among the `allowed` its kind has used least so far,
    never one a near neighbour of its kind (within 25 m) already has, so no two alike stand together."""
    kin = [h for h in houses if h["type"] == "A" and h["variant"] == variant]
    near = {h["seed"] for h in kin if math.hypot(h["pos"][0] - x, h["pos"][1] - y) < 25.0}
    free = [s for s in allowed if s not in near] or list(allowed)
    used = {s: sum(1 for h in kin if h["seed"] == s) for s in free}
    return random.Random(hid + ":variant").choice([s for s in free if used[s] == min(used.values())])


def side_lanes(groups, houses, blocked, up, along, z_at):
    """The gap between two neighbouring groups of a row, where both houses at it were placed, as a lane up to the next
    row's front apron: level at the lower house's pad, then a flight (about 0.2 m risers, 0.25 m treads; pads.py
    lane_flight) whose top meets the pad of the house the lane ends at (or the ground). Stopped short of any building in its way; dropped where the flight
    does not fit (more than 10 m of rise, or longer than the lane), and within 9 m of the Sky Stair (four had run up it).
    pads.py settles each lane's head on the padded ground."""
    feet = [rect(h["pos"][0], h["pos"][1], h["footprint"][0], h["footprint"][1], h["rot_deg"], 0.3) for h in houses]
    pads = [h["pos"][2] for h in houses]
    lanes, skipped = [], 0
    ids = sorted(groups)
    for ga, gb in zip(ids, ids[1:]):
        A, Bg = groups[ga], groups[gb]
        if A["k"] != Bg["k"] or (A["size"] - 1) not in A["houses"] or 0 not in Bg["houses"]:
            continue
        ha, hb = A["houses"][A["size"] - 1], Bg["houses"][0]
        (xa, ya, za), (xb, yb, zb_) = ha["pos"], hb["pos"]
        gap = (xb - xa) * along[0] + (yb - ya) * along[1] - (ha["footprint"][0] + hb["footprint"][0]) / 2
        if gap < 2.6:
            continue
        mx, my = (xa + xb) / 2, (ya + yb) / 2
        depth = max(ha["footprint"][1], hb["footprint"][1])
        fx, fy = mx - up[0] * (depth / 2 + 1.5), my - up[1] * (depth / 2 + 1.5)  # the lane's foot: the row's front apron
        if min(seg_dist((fx + up[0] * s, fy + up[1] * s), *SKY_STAIR) for s in (0.0, ROW / 2, ROW)) < 9.0:
            continue  # the gap either side of the Sky Stair is the stair itself
        width = min(gap - 0.3, P.LANE_MAX)  # (two groups far apart along a row: LN-036 had been 31.7 m wide)
        # up the lane until something stands in it: a house's footprint, or a named building's ground
        L, z_top, head = ROW, None, None
        for s in np.arange(depth + 2.0, ROW + 0.01, 0.5):
            cx, cy = fx + up[0] * s, fy + up[1] * s
            probe = rect(cx, cy, width, 0.5, FACING)
            hit = [i for i, q in enumerate(feet) if overlap(probe, q)]
            if hit or any(overlap(probe, q) for q in blocked):
                L = s - 1.5
                z_top = max(pads[i] for i in hit) if hit else None
                head = houses[max(hit, key=lambda i: pads[i])]["id"] if hit else None
                break
        tx, ty = fx + up[0] * L, fy + up[1] * L
        if z_top is None:
            z_top = z_at(tx, ty)
        z_a = min(za, zb_)
        rise = z_top - z_a
        if not math.isfinite(rise) or rise < -0.3:
            skipped += 1
            continue
        if rise >= 0.3:  # the lanes as first laid out, for whole metres of the kit's lane_stair (their ids kept)
            m = int(math.ceil(rise - 0.05))
            if m > 10 or L - 0.6 - m / LANE_RISE * LANE_RUN < 0.5:
                skipped += 1
                continue
        flight = P.lane_flight("LN-%03d" % (len(lanes) + 1), L, z_a, z_top)  # its own, exactly from foot to head
        lanes.append({"id": "LN-%03d" % (len(lanes) + 1), "row": A["k"], "from": [round(fx, 2), round(fy, 2)], "dir": [round(up[0], 4), round(up[1], 4)],
                      "length": round(L, 2), "width": round(width, 2), "z_a": round(z_a, 2), "z_b": round(z_top, 2), "flight": flight or None,
                      "between": [ha["id"], hb["id"]], "head": head})
    return lanes, skipped


